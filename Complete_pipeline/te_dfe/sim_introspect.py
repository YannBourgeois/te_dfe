def write_theta(out_path: Path, theta, param_names: Sequence[str],
                  param_labels: Sequence[str]) -> None:
    with open(out_path, "w") as f:
        f.write("idx\tname\tlabel\traw\n")
        for i, (n, lbl) in enumerate(zip(param_names, param_labels)):
            f.write(f"{i}\t{n}\t{lbl}\t{float(theta[i]):.8f}\n")


def write_window_artifacts(
    workdir: Path,
    window_idx: int,
    ts: tskit.TreeSequence,
    schedule: List[Tuple[int, int]],
    covariate: np.ndarray,
    sim_length: int,
    maf_min: float,
) -> None:
    """
    Write per-window TSVs to workdir for one window.

    Parameters
    ----------
    workdir       : the per-replicate directory (already created)
    window_idx    : 0-based window index for naming
    ts            : the post-recapitation tree sequence
    schedule      : list of (slim_gen, position) — what was passed to SLiM
    covariate     : 4-vector [gene_density, recomb, te_density, snp_density]
    sim_length    : SIM_LENGTH (so we can convert slim_time to age in gens-ago)
    maf_min       : MAF threshold (so we report which SNPs the processor uses)
    """
    workdir.mkdir(parents=True, exist_ok=True)
    suffix = f"window_{window_idx:02d}"

    # Schedule. In the rate-driven model this is empty (SLiM generates
    # insertions natively from a per-bp rate map); kept for diagnostic
    # parity with the older schedule-driven pipeline.
    with open(workdir / f"schedule_{suffix}.tsv", "w") as f:
        f.write("slim_gen\tposition\n")
        for gen, pos in schedule:
            f.write(f"{gen}\t{pos}\n")

    # TEs that survived to present
    te_rows = []
    snp_rows = []
    for var in ts.variants():
        muts = list(var.site.mutations)
        any_te = any(_is_te_mut(m) for m in muts)
        genos = var.genotypes
        freq = float(genos.mean())
        if any_te:
            origin, s = _slim_metadata(muts[0])
            age_gens_ago = sim_length - origin if origin > 0 else float("nan")
            te_rows.append((
                int(var.site.id),                      # site id
                float(var.site.position),
                float(origin),                          # in SLiM gen units (1..SIM_END)
                float(age_gens_ago),
                float(s),
                float(2 * 50000 * s),                  # 2Ne·s assuming 50k (rough; for binning)
                freq,
            ))
        else:
            if min(freq, 1.0 - freq) >= maf_min:
                snp_rows.append((float(var.site.position), freq))

    with open(workdir / f"tes_{suffix}.tsv", "w") as f:
        f.write("site_id\tposition\tslim_time_origin\tage_gens_ago\ts\t2Ne_50k_times_s\tpresent_day_freq\n")
        for row in te_rows:
            f.write("\t".join(f"{x}" for x in row) + "\n")

    with open(workdir / f"snps_{suffix}.tsv", "w") as f:
        f.write("position\tpresent_day_freq\n")
        for pos, freq in snp_rows:
            f.write(f"{pos:.1f}\t{freq:.6f}\n")

    # Per-window summary statistics
    n_te = len(te_rows)
    n_snp = len(snp_rows)
    if n_te > 0:
        ages = [r[3] for r in te_rows if not np.isnan(r[3])]
        s_vals = [r[4] for r in te_rows]
        freqs_te = [r[6] for r in te_rows]
        mean_age = float(np.mean(ages)) if ages else float("nan")
        std_age  = float(np.std(ages))  if ages else float("nan")
        mean_s   = float(np.mean(s_vals))
        n_neutral = sum(1 for s in s_vals if s == 0.0)
        mean_freq_te = float(np.mean(freqs_te))
    else:
        mean_age = std_age = mean_s = mean_freq_te = float("nan")
        n_neutral = 0

    if n_snp > 0:
        freqs_snp = [r[1] for r in snp_rows]
        mean_freq_snp = float(np.mean(freqs_snp))
    else:
        mean_freq_snp = float("nan")

    with open(workdir / f"summary_{suffix}.tsv", "w") as f:
        f.write("statistic\tvalue\n")
        f.write(f"window_idx\t{window_idx}\n")
        f.write(f"n_te_surviving\t{n_te}\n")
        f.write(f"n_te_neutral\t{n_neutral}\n")
        f.write(f"n_te_deleterious\t{n_te - n_neutral}\n")
        f.write(f"mean_age_gens_ago\t{mean_age:.2f}\n")
        f.write(f"std_age_gens_ago\t{std_age:.2f}\n")
        f.write(f"mean_s\t{mean_s:.6f}\n")
        f.write(f"mean_te_freq\t{mean_freq_te:.4f}\n")
        f.write(f"n_snp_above_maf\t{n_snp}\n")
        f.write(f"mean_snp_freq\t{mean_freq_snp:.4f}\n")
        f.write(f"covariate_gene_density\t{covariate[0]:.6f}\n")
        f.write(f"covariate_recomb_scaled\t{covariate[1]:.6f}\n")
        f.write(f"covariate_te_density\t{covariate[2]:.4f}\n")
        f.write(f"covariate_snp_density\t{covariate[3]:.4f}\n")


def write_substituted_slim_script(
    out_path: Path,
    template_path: str,
    seq_len: int,
    sim_end: int,
    lam: float,
    gamma_shape: float,
    mean_s: float,
    burst_tick_start: int,
    burst_tick_end: int,
    multiplier: float,
    demog_path: str,
    recomb_path: str,
    output_path: str,
    seed: int,
) -> None:
    """
    Materialize the SLiM script with -d substitutions inlined as Eidos
    constants, so the result can be loaded into SLiMGUI for inspection.
    """
    with open(template_path) as f:
        body = f.read()
    header_lines = [
        "// === Materialized SLiM script (debug dump) ===",
        f"// seed = {seed}",
        f"// To run in SLiMGUI: open this file directly.",
        "//",
        "// Inlined -d definitions (these would normally be passed via the",
        "// command line but are baked in here for SLiMGUI inspection):",
        "//",
        f'defineConstant("SEQ_LEN",          {int(seq_len)});',
        f'defineConstant("SIM_END",          {int(sim_end)});',
        f'defineConstant("LAMBDA",           {lam:.10e});',
        f'defineConstant("GAMMA_SHAPE",      {gamma_shape:.8f});',
        f'defineConstant("MEAN_S",           {mean_s:.8f});',
        f'defineConstant("BURST_TICK_START", {int(burst_tick_start)});',
        f'defineConstant("BURST_TICK_END",   {int(burst_tick_end)});',
        f'defineConstant("MULTIPLIER",       {multiplier:.6f});',
        f'defineConstant("DEMOG_PATH",       "{demog_path}");',
        f'defineConstant("RECOMB_PATH",      "{recomb_path}");',
        f'defineConstant("OUTPUT_PATH",      "{output_path}");',
        "// === End of inlined definitions ===",
        "",
    ]
    with open(out_path, "w") as f:
        f.write("\n".join(header_lines))
        f.write("\n")
        f.write(body)
