"""
sim_introspect.py — Per-simulation introspection for debugging and validation.

When `--debug-dump <DIR>` is passed to 01_simulate.py, writes a folder per
replicate under <DIR>/sim_NNNNNN/ containing:

  - theta.txt              : the 12-dim parameter vector with named columns
  - schedule_window_W.tsv  : the (gen, pos) schedule that was passed to SLiM
  - tes_window_W.tsv       : per-surviving-TE info from the tree sequence:
                             (insertion_id, true_origin_gen, true_s,
                              present_day_freq, position)
  - snps_window_W.tsv      : per-surviving-SNP info: (position, frequency)
  - summary_window_W.tsv   : per-window summary stats (n_te, mean_freq,
                             mean_age, std_age, n_snp, mean_snp_freq, ...)
  - slim_substituted.txt   : the SLiM script with -d substitutions inlined,
                             so it can be loaded directly into SLiMGUI
  - covariates.tsv         : the 4-element covariate vector per window
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import List, Sequence, Tuple

import numpy as np
import tskit


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _is_te_mut(mut):
    """
    True iff this mutation was generated by SLiM (vs. a neutral SNP
    laid down by msprime's overlay).

    SLiM mutations carry metadata of the form
        {"mutation_list": [{"selection_coeff": ..., "slim_time": ..., ...}],
         "tmp_neutral": ...}
    Neutral overlay mutations from msprime have either no metadata or
    metadata that's an empty / default-decoded dict from the site schema.

    The tight test: there's a non-empty mutation_list with a slim_time
    field present. This works regardless of how the metadata schema
    decodes empty bytes (some schemas decode b'' to a populated default
    dict, breaking a naive `bool(metadata)` test).
    """
    meta = mut.metadata
    if not isinstance(meta, dict):
        return False
    ml = meta.get("mutation_list")
    if not ml:
        return False
    # SLiM always writes slim_time per mutation; msprime overlays never do
    return "slim_time" in ml[0]


def _slim_metadata(mut) -> Tuple[float, float]:
    """Extract (origin_gen_in_slim_units, selection_coeff) from SLiM metadata."""
    meta = mut.metadata
    sel = 0.0
    origin = -1.0
    if isinstance(meta, dict):
        if "mutation_list" in meta and meta["mutation_list"]:
            ml = meta["mutation_list"][0]
            sel    = float(ml.get("selection_coeff", 0.0))
            origin = float(ml.get("slim_time", -1.0))
        else:
            sel    = float(meta.get("selection_coeff", 0.0))
            origin = float(meta.get("slim_time", -1.0))
    return origin, sel


